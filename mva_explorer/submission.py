"""Submission-facing representation helpers.

These functions do not alter model ranking or scores. They only preserve an
already-generated multi-allelic hypothesis when the gene-level strict ranking
would otherwise display only the strongest single allele.
"""
from __future__ import annotations


PASS_QC = {"QC_PASS", "QC_STRONG"}


def _split(value):
    return [x for x in str(value or "").split(";") if x]


def select_submission_representation(strict_row, ranking_rows, qc_by_key):
    """Return a transparent submission representation for one strict gene row.

    The strict row remains the source of gene rank and score. A two-allele AR
    hypothesis may be used only for representation when:
      * it was already generated by the ranking layer,
      * it contains the strict row's contributing variant(s),
      * it contains exactly two distinct variants,
      * both variants pass technical QC, and
      * phase is TRANS or UNRESOLVED (never CIS).

    UNRESOLVED pairs remain explicitly unphased and receive no ranking bonus.
    """
    gene = strict_row["gene"]
    strict_keys = _split(strict_row.get("variant_keys"))

    eligible = []
    for row in ranking_rows:
        if row.get("gene") != gene or row.get("moi") != "AR":
            continue
        keys = _split(row.get("variant_keys"))
        if len(keys) != 2 or len(set(keys)) != 2:
            continue
        if strict_keys and not set(strict_keys).issubset(set(keys)):
            continue
        phase = str(row.get("phase_status") or "").upper()
        if phase not in {"TRANS", "UNRESOLVED"}:
            continue
        statuses = [qc_by_key.get(k, "QC_UNKNOWN") for k in keys]
        if any(s not in PASS_QC for s in statuses):
            continue
        eligible.append((float(row.get("combined_score") or 0), row, statuses))

    out = {
        "gene": gene,
        "ranking_id": strict_row.get("id", ""),
        "ranking_moi": strict_row.get("moi", ""),
        "ranking_combined_score": strict_row.get("combined_score", ""),
        "ranking_variant_keys": strict_row.get("variant_keys", ""),
        "submission_id": strict_row.get("id", ""),
        "submission_moi": strict_row.get("moi", ""),
        "submission_phase_status": strict_row.get("phase_status", ""),
        "submission_variant_keys": strict_row.get("variant_keys", ""),
        "submission_effects": strict_row.get("effects", ""),
        "submission_qc_variant_statuses": ";".join(
            qc_by_key.get(k, "QC_UNKNOWN") for k in strict_keys
        ),
        "representation_status": "STRICT_RANKING_HYPOTHESIS",
        "ranking_score_unchanged": "TRUE",
    }

    if not eligible:
        return out

    _, pair, statuses = max(eligible, key=lambda x: x[0])
    phase = str(pair.get("phase_status") or "").upper()
    out.update({
        "submission_id": pair.get("id", ""),
        "submission_moi": "AR_CANDIDATE_PAIR",
        "submission_phase_status": phase,
        "submission_variant_keys": pair.get("variant_keys", ""),
        "submission_effects": pair.get("effects", ""),
        "submission_qc_variant_statuses": ";".join(statuses),
        "representation_status": (
            "CONFIRMED_TRANS_PAIR" if phase == "TRANS"
            else "CANDIDATE_UNPHASED_PAIR"
        ),
    })
    return out
